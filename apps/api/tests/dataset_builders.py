"""Synthetic dataset builders for the manifest tooling tests.

Everything here is generated on the fly into a temporary directory: fake image
bytes (a JPEG signature plus a unique text payload) and manifests that describe
them. No real photograph, dataset or restricted record is read or needed.
"""

import copy
import hashlib
import os
import subprocess
from pathlib import Path
from typing import Any

CATEGORIES = ("synthetic-category-a", "synthetic-category-b", "synthetic-category-c")
PERMITTED_USES = ["training", "validation", "testing"]
LICENCE_SNAPSHOT_PATH = "licence/licence-snapshot.txt"
LICENCE_SNAPSHOT_TEXT = b"Synthetic licence text for the test suite. Not a real licence.\n"


def fake_image_bytes(label: str) -> bytes:
    return b"\xff\xd8\xff\xe0synthetic-test-fixture:" + label.encode("utf-8")


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def base_manifest(**dataset_overrides: Any) -> dict[str, Any]:
    """A valid schema-1.1 manifest header with no records yet."""
    dataset: dict[str, Any] = {
        "dataset_id": "synthetic-fixture",
        "name": "Synthetic test fixture",
        "description": "Generated for automated tests. Not real data.",
        "category": "synthetic",
        "source": {"name": "Generated by the test suite"},
        "licence": {
            "name": "Synthetic test fixture; no real data",
            "version": "fixture-1",
            "evidence": {
                "captured_on": "2026-01-01",
                "reference": "synthetic-test-fixture; generated by the test suite",
            },
        },
        "permissions": {
            "status": "approved",
            "permitted_uses": list(PERMITTED_USES),
            "commercial_training": "unknown",
            "reviewed_by": "synthetic-test-fixture",
            "reviewed_on": "2026-02-01",
        },
        "sample_identity": {"basis": "recorded_by_collector"},
        "label_vocabulary": {
            "vocabulary_id": "synthetic-vocabulary",
            "version": "1",
            "categories": list(CATEGORIES),
        },
    }
    dataset.update(dataset_overrides)
    return {"schema_version": "1.1", "dataset": dataset, "records": []}


def field_governance(**overrides: Any) -> dict[str, Any]:
    """A resolved Ghana field-governance record made of placeholders.

    Nothing here is a real permission, consent or review: it is fictional text for tests.
    """
    record: dict[str, Any] = {
        "collection_permission": {
            "status": "documented",
            "granted_by": "synthetic-fixture-authority",
            "reference": "synthetic-fixture-permission-1",
            "recorded_on": "2026-01-15",
        },
        "consent": {
            "status": "not_applicable",
            "basis": "Synthetic fixture: no people or private land appear in these generated files.",
        },
        "location_privacy": {"handling": "removed"},
        "reviewed_by": "synthetic-test-fixture",
        "reviewed_on": "2026-02-01",
        "permitted_uses": list(PERMITTED_USES),
    }
    record.update(overrides)
    return record


def make_record(
    record_id: str,
    sample_id: str,
    *,
    session_id: str | None = None,
    category: str | None = CATEGORIES[0],
    split: str = "unassigned",
    data: bytes | None = None,
    relative_path: str | None = None,
) -> tuple[dict[str, Any], bytes, str]:
    """A record, the bytes of its file, and its relative path."""
    content = data if data is not None else fake_image_bytes(record_id)
    path = relative_path or f"images/{sample_id}/{record_id}.jpg"
    record: dict[str, Any] = {
        "record_id": record_id,
        "physical_sample_id": sample_id,
        "file": {
            "filename": path.rsplit("/", 1)[-1],
            "relative_path": path,
            "sha256": sha256_hex(content),
            "size_bytes": len(content),
            "media_type": "image/jpeg",
        },
        "split": split,
    }
    if session_id is not None:
        record["capture_session_id"] = session_id
    if category is not None:
        record["label"] = {
            "material_category": category,
            "source": {"type": "human_visual", "description": "Synthetic fixture label."},
        }
    return record, content, path


def build_dataset(
    root: Path,
    *,
    sample_count: int = 12,
    images_per_sample: int = 3,
    categories: tuple[str, ...] = CATEGORIES,
    sessions: str = "per_sample",
    **dataset_overrides: Any,
) -> dict[str, Any]:
    """Write fake image files under `root` and return a manifest that describes them.

    `sessions`: "per_sample" gives each sample its own capture session, "none"
    records no session IDs, "shared_pairs" puts samples 2k and 2k+1 in one session.
    """
    manifest = base_manifest(**dataset_overrides)
    evidence = manifest["dataset"]["licence"].get("evidence")
    if evidence is not None and "snapshot" not in evidence:
        # A use is only accepted against a checksummed licence snapshot, so the fixture has one.
        snapshot = root / LICENCE_SNAPSHOT_PATH
        snapshot.parent.mkdir(parents=True, exist_ok=True)
        snapshot.write_bytes(LICENCE_SNAPSHOT_TEXT)
        evidence["snapshot"] = {
            "relative_path": LICENCE_SNAPSHOT_PATH,
            "sha256": sha256_hex(LICENCE_SNAPSHOT_TEXT),
        }
    for sample_index in range(sample_count):
        sample_id = f"sample-{sample_index:03d}"
        category = categories[sample_index % len(categories)]
        if sessions == "per_sample":
            session_id: str | None = f"session-{sample_index:03d}"
        elif sessions == "shared_pairs":
            session_id = f"session-{sample_index // 2:03d}"
        else:
            session_id = None
        for image_index in range(images_per_sample):
            record_id = f"rec-{sample_index:03d}-{image_index}"
            record, content, path = make_record(
                record_id, sample_id, session_id=session_id, category=category
            )
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
            manifest["records"].append(record)
    return manifest


def link_directory(link: Path, target: Path) -> bool:
    """Make `link` point at `target`: a symlink, or on Windows a junction (no privilege needed)."""
    try:
        link.symlink_to(target, target_is_directory=True)
        return True
    except (OSError, NotImplementedError):
        pass
    if os.name == "nt":
        junction = subprocess.run(
            ["cmd", "/c", "mklink", "/J", str(link), str(target)],
            capture_output=True,
            check=False,
        )
        return junction.returncode == 0
    return False


def filesystem_is_case_sensitive(directory: Path) -> bool:
    """True if this file system treats 'a' and 'A' as different names (probed in `directory`)."""
    probe = directory / "case-probe-lower"
    probe.write_bytes(b"x")
    try:
        return not (directory / "CASE-PROBE-LOWER").exists()
    finally:
        probe.unlink()


def clone(manifest: dict[str, Any]) -> dict[str, Any]:
    return copy.deepcopy(manifest)


def record_by_id(manifest: dict[str, Any], record_id: str) -> dict[str, Any]:
    return next(record for record in manifest["records"] if record["record_id"] == record_id)


def set_splits(manifest: dict[str, Any], assignment: dict[str, str]) -> dict[str, Any]:
    """Return a copy where each physical sample in `assignment` has that split."""
    result = clone(manifest)
    for record in result["records"]:
        if record["physical_sample_id"] in assignment:
            record["split"] = assignment[record["physical_sample_id"]]
    return result
